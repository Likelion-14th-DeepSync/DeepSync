CREATE TABLE analysis_confidence_results (
    id BIGINT NOT NULL AUTO_INCREMENT,
    member_id BIGINT NOT NULL,
    score INT NOT NULL,
    confidence_level VARCHAR(20) NOT NULL,
    image_quality_score INT NOT NULL,
    image_quality_available BOOLEAN NOT NULL,
    skin_record_coverage_score INT NOT NULL,
    lifestyle_completeness_score INT NOT NULL,
    environment_completeness_score INT NOT NULL,
    repeated_observation_score INT NOT NULL,
    repeated_observation_available BOOLEAN NOT NULL,
    experiment_evidence_score INT NOT NULL,
    experiment_evidence_available BOOLEAN NOT NULL,
    model_confidence_score INT NOT NULL,
    model_confidence_available BOOLEAN NOT NULL,
    skin_recorded_days INT NOT NULL,
    reasons VARCHAR(1500) NOT NULL,
    next_actions VARCHAR(1500) NOT NULL,
    analyzed_from DATE NOT NULL,
    analyzed_to DATE NOT NULL,
    calculated_at DATETIME(6) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_analysis_confidence_member UNIQUE (member_id),
    CONSTRAINT fk_analysis_confidence_member
        FOREIGN KEY (member_id) REFERENCES members (id) ON DELETE CASCADE
);
