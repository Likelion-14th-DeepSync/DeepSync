CREATE TABLE lifestyle_experiment_results (
    id BIGINT NOT NULL AUTO_INCREMENT,
    experiment_id BIGINT NOT NULL,
    evaluated_days INT NOT NULL,
    achieved_days INT NOT NULL,
    missing_days INT NOT NULL,
    achievement_rate DECIMAL(5,1) NOT NULL,
    before_analysis_count INT NOT NULL,
    after_analysis_count INT NOT NULL,
    before_redness_score DECIMAL(5,1) NOT NULL,
    after_redness_score DECIMAL(5,1) NOT NULL,
    before_trouble_score DECIMAL(5,1) NOT NULL,
    after_trouble_score DECIMAL(5,1) NOT NULL,
    before_dryness_score DECIMAL(5,1) NOT NULL,
    after_dryness_score DECIMAL(5,1) NOT NULL,
    before_tone_uniformity_score DECIMAL(5,1) NOT NULL,
    after_tone_uniformity_score DECIMAL(5,1) NOT NULL,
    before_overall_score DECIMAL(5,1) NOT NULL,
    after_overall_score DECIMAL(5,1) NOT NULL,
    most_changed_metric VARCHAR(30) NOT NULL,
    most_changed_amount DECIMAL(5,1) NOT NULL,
    change_direction VARCHAR(20) NOT NULL,
    confidence_level VARCHAR(20) NOT NULL,
    recommendation VARCHAR(30) NOT NULL,
    confidence_reasons VARCHAR(1000) NOT NULL,
    summary VARCHAR(500) NOT NULL,
    calculated_at DATETIME(6) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_lifestyle_experiment_results_experiment UNIQUE (experiment_id),
    CONSTRAINT fk_lifestyle_experiment_results_experiment
        FOREIGN KEY (experiment_id) REFERENCES lifestyle_experiments (id) ON DELETE CASCADE
);
